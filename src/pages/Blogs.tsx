const Blogs = () => {
  const [selectedWriting, setSelectedWriting] = useState<Writing | null>(null);
  const [writingEntries, setWritingEntries] = useState<Writing[]>(
    fallbackWritings
  );
  const [selectedAuthor, setSelectedAuthor] = useState<string>("అందరూ");
  const [visibleCount, setVisibleCount] = useState(6);

  const handleLoadMore = () => {
    setVisibleCount((prev) => prev + 3);
  };

  const authors = [
    "అందరూ",
    ...Array.from(
      new Set(writingEntries.map((w) => w.author.trim()).filter(Boolean))
    ),
  ];

  const filteredWritings =
    selectedAuthor === "అందరూ"
      ? writingEntries
      : writingEntries.filter((w) => w.author.trim() === selectedAuthor);

  // Close modal with ESC key
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") setSelectedWriting(null);
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, []);

  useEffect(() => {
    fetchAdminList<Writing[]>("writings", []).then((data) => {
      if (!data || data.length === 0) {
        return;
      }
      const normalized = data.map((entry, index) => ({
        id: entry.id ?? index + 1,
        title: entry.title ?? "",
        author: entry.author ?? "",
        year: entry.year ?? "",
        type: entry.type ?? "",
        content: entry.content ?? "",
      }));
      const mergedMap = new Map<string, Writing>();
      const mergeKey = (entry: Writing) =>
        `${entry.title}__${entry.author}__${entry.year}__${entry.type}`;

      fallbackWritings.forEach((entry) => {
        mergedMap.set(mergeKey(entry), entry);
      });

      normalized.forEach((entry) => {
        mergedMap.set(mergeKey(entry), entry);
      });

      setWritingEntries(Array.from(mergedMap.values()));
    });
  }, []);

  return (
    <div className="min-h-screen font-telugu">
      <Navbar />
      <main className="pt-24 pb-12">
        {/* Header */}
        <section className="text-center px-6 max-w-5xl mx-auto space-y-6">
          <h1 className="text-5xl font-extrabold text-[#811414]">
            మా సృజనాత్మక రచనలు
          </h1>
          <p className="text-lg text-[#4f4f4f]">
            మా కూటమి సభ్యుల కలం నుండి జారిన భావాలు – కవితలు, కథలు, అనుభవాలు.
          </p>
          <div className="h-1 w-24 bg-[#811414] mx-auto rounded-full"></div>
        </section>

        {/* Writer Filter */}
        <section className="mt-10 px-6 max-w-5xl mx-auto text-center">
          <p className="text-sm font-semibold text-[#811414] uppercase tracking-wider mb-4">
            రచయిత ద్వారా ఎంచుకోండి
          </p>
          <div className="flex flex-wrap items-center justify-center gap-3">
            {authors.map((author) => {
              const isSelected = selectedAuthor === author;
              const count =
                author === "అందరూ"
                  ? writingEntries.length
                  : writingEntries.filter((w) => w.author.trim() === author).length;
              return (
                <button
                  key={author}
                  onClick={() => {
                    setSelectedAuthor(author);
                    setVisibleCount(6);
                  }}
                  className={`px-4 py-2 rounded-full text-sm font-medium transition-all duration-200 shadow-sm flex items-center gap-2 ${
                    isSelected
                      ? "bg-[#811414] text-white shadow-md scale-105"
                      : "bg-[#fff9f4] text-[#4f4f4f] border border-[#e6d4c5] hover:bg-[#811414] hover:text-white"
                  }`}
                >
                  <span>✍ {author}</span>
                  <span
                    className={`text-xs px-2 py-0.5 rounded-full ${
                      isSelected
                        ? "bg-white text-[#811414]"
                        : "bg-[#e6d4c5] text-[#2d2d2d]"
                    }`}
                  >
                    {count}
                  </span>
                </button>
              );
            })}
          </div>
        </section>

        {/* Cards */}
        <section className="mt-12 px-6 max-w-6xl mx-auto grid gap-10 sm:grid-cols-2 lg:grid-cols-3 auto-rows-fr">
          {filteredWritings.slice(0, visibleCount).map((writing, index) => (
            <motion.div
              key={writing.id}
              initial={{ opacity: 0, y: 30 }}
              whileInView={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.4, delay: index * 0.1 }}
              viewport={{ once: true }}
              className="rounded-xl shadow-md hover:shadow-xl transition-shadow duration-300 border border-[#e6d4c5] bg-[#fff9f4] p-6 flex flex-col justify-between h-full"
            >
              <div className="flex-grow">
                <div className="flex items-center justify-between mb-2">
                  <h3 className="text-2xl font-semibold text-[#811414]">
                    {writing.title}
                  </h3>
                  <span className="text-xs font-bold bg-[#811414] text-white px-2 py-1 rounded-full">
                    {writing.type}
                  </span>
                </div>
                <p className="text-lg text-[#444] mb-2">
                  ✍ <span className="font-medium text-[#2d2d2d]">{writing.author}</span>{" "}
                  <span className="text-xs text-[#777]">({writing.year})</span>
                </p>
                {/* Preview only */}
                <p className="text-base leading-relaxed tracking-wide text-justify text-[#3f3f3f] line-clamp-4">
                  {writing.content.trim()}
                </p>
              </div>
              <div className="mt-4 text-right">
                <button
                  onClick={() => setSelectedWriting(writing)}
                  className="text-sm text-[#811414] hover:text-[#5e0f0f] hover:scale-105 hover:underline transition-transform duration-200 ease-in-out"
                >
                  పూర్తిగా చదవండి →
                </button>
              </div>
            </motion.div>
          ))}

          {/* Load More */}
          {visibleCount < filteredWritings.length && (
            <div className="col-span-full text-center mt-10">
              <button
                onClick={handleLoadMore}
                className="px-6 py-2 rounded-full text-white transition hover:opacity-90"
                style={{ backgroundColor: "#811414" }}
              >
                ఇంకా చూపించు
              </button>
            </div>
          )}
        </section>
      </main>

      <Footer />

      {/* Modal */}
      <AnimatePresence>
        {selectedWriting && (
          <motion.div
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="fixed inset-0 z-50 flex items-center justify-center bg-black bg-opacity-50 backdrop-blur-sm"
            onClick={() => setSelectedWriting(null)}
          >
            <motion.div
              initial={{ scale: 0.9, opacity: 0 }}
              animate={{ scale: 1, opacity: 1 }}
              exit={{ scale: 0.9, opacity: 0 }}
              transition={{ duration: 0.3 }}
              className="rounded-xl shadow-lg max-w-3xl w-full max-h-[80vh] overflow-y-auto p-8 m-4 relative"
              style={{ backgroundColor: "#fff9f4", color: "#2d2d2d" }}
              onClick={(e) => e.stopPropagation()}
            >
              {/* Close Button */}
              <button
                className="absolute top-3 right-4 text-[#811414] text-xl font-bold hover:text-[#5e0f0f]"
                onClick={() => setSelectedWriting(null)}
              >
                ×
              </button>

              <h2 className="text-3xl font-bold mb-2 text-[#811414]">
                {selectedWriting.title}
              </h2>
              <p className="text-sm text-[#555] mb-6">
                ✍ {selectedWriting.author} ({selectedWriting.year}) | {selectedWriting.type}
              </p>
              <div className="text-base leading-relaxed tracking-wide text-justify whitespace-pre-line space-y-4">
                {selectedWriting.content.trim()}
              </div>
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
};

export default Blogs;
